func TestExtractActions(t *testing.T) {
	// Test case 1: root-level action: "run" with batch file in files
	payload1 := &ExtractedPayload{
		Action: "run",
		Files: []ExtractedFile{
			{Filename: "script.bat", Code: "@echo off\necho hello"},
		},
	}
	actions1 := extractActions(payload1, []string{"script.bat"})
	if len(actions1) != 1 {
		t.Fatalf("Expected 1 action, got %d", len(actions1))
	}
	if actions1[0].Target != "script.bat" || actions1[0].Type != "run" {
		t.Fatalf("Expected action target 'script.bat' and type 'run', got %+v", actions1[0])
	}

	// Test case 2: file-level action: "run"
	payload2 := &ExtractedPayload{
		Files: []ExtractedFile{
			{Filename: "setup.bat", Code: "@echo off", Action: "run"},
			{Filename: "readme.txt", Code: "hello"},
		},
	}
	actions2 := extractActions(payload2, []string{"setup.bat", "readme.txt"})
	if len(actions2) != 1 {
		t.Fatalf("Expected 1 action, got %d", len(actions2))
	}
	if actions2[0].Target != "setup.bat" {
		t.Fatalf("Expected action target 'setup.bat', got %s", actions2[0].Target)
	}

	// Test case 3: actions array
	payload3 := &ExtractedPayload{
		Actions: []any{
			map[string]any{"type": "run", "target": "task1.bat"},
			"run task2.bat",
		},
	}
	actions3 := extractActions(payload3, nil)
	if len(actions3) != 2 {
		t.Fatalf("Expected 2 actions, got %d", len(actions3))
	}
	if actions3[0].Target != "task1.bat" || actions3[1].Target != "task2.bat" {
		t.Fatalf("Expected task1.bat and task2.bat, got %+v", actions3)
	}
}

func TestExecuteActionSilently_BatchScript(t *testing.T) {
	_ = os.MkdirAll("Sandbox", 0755)

	var scriptName string
	var scriptContent string

	if runtime.GOOS == "windows" {
		scriptName = "test_run.bat"
		scriptContent = "@echo off\necho Step 1: Starting batch process...\necho Step 2: Running silent operations...\necho Step 3: Done!\n"
	} else {
		scriptName = "test_run.sh"
		scriptContent = "#!/bin/sh\necho 'Step 1: Starting batch process...'\necho 'Step 2: Running silent operations...'\necho 'Step 3: Done!'\n"
	}

	scriptPath := filepath.Join("Sandbox", scriptName)
	if err := os.WriteFile(scriptPath, []byte(scriptContent), 0755); err != nil {
		t.Fatalf("Failed to create test script: %v", err)
	}
	defer os.Remove(scriptPath)

	action := ActionItem{
		Type:       "run",
		Target:     scriptName,
		WorkingDir: "Sandbox",
	}

	result := executeActionSilently(action)
	if !result.Success {
		t.Fatalf("Execution failed: %v (ExitCode: %d, Output: %s)", result.Error, result.ExitCode, result.Output)
	}

	if !strings.Contains(result.Output, "Step 1: Starting batch process...") {
		t.Fatalf("Expected output to contain 'Step 1: Starting batch process...', got:\n%s", result.Output)
	}
	if !strings.Contains(result.Output, "Step 3: Done!") {
		t.Fatalf("Expected output to contain 'Step 3: Done!', got:\n%s", result.Output)
	}

	// Verify execution.log was written
	logPath := filepath.Join("Sandbox", "execution.log")
	logData, err := os.ReadFile(logPath)
	if err != nil {
		t.Fatalf("Failed to read execution.log: %v", err)
	}
	if !strings.Contains(string(logData), "EXECUTION STARTED") {
		t.Fatalf("Expected execution.log to contain 'EXECUTION STARTED', got:\n%s", string(logData))
	}
	if !strings.Contains(string(logData), "Step 2: Running silent operations...") {
		t.Fatalf("Expected execution.log to contain logged lines, got:\n%s", string(logData))
	}
}

