func TestModelManagement_GrokClaudeGemini(t *testing.T) {
	// Test setActiveModel
	setActiveModel("grok")
	if m := getActiveModel(); m != "grok" {
		t.Errorf("Expected active model 'grok', got %s", m)
	}

	setActiveModel("x")
	if m := getActiveModel(); m != "grok" {
		t.Errorf("Expected active model 'grok' for alias 'x', got %s", m)
	}

	setActiveModel("gemini")
	if m := getActiveModel(); m != "gemini" {
		t.Errorf("Expected active model 'gemini', got %s", m)
	}

	setActiveModel("claude")
	if m := getActiveModel(); m != "claude" {
		t.Errorf("Expected active model 'claude', got %s", m)
	}

	// Test 3-way toggle cycle
	setActiveModel("claude")
	if next := toggleActiveModel(); next != "gemini" {
		t.Errorf("Expected next model after claude to be 'gemini', got %s", next)
	}
	if next := toggleActiveModel(); next != "grok" {
		t.Errorf("Expected next model after gemini to be 'grok', got %s", next)
	}
	if next := toggleActiveModel(); next != "claude" {
		t.Errorf("Expected next model after grok to be 'claude', got %s", next)
	}

	// Test Display Names
	if name := getProviderDisplayName("grok"); name != "Grok" {
		t.Errorf("Expected display name 'Grok', got %s", name)
	}
	if name := getProviderDisplayName("gemini"); name != "Gemini" {
		t.Errorf("Expected display name 'Gemini', got %s", name)
	}
	if name := getProviderDisplayName("claude"); name != "Claude" {
		t.Errorf("Expected display name 'Claude', got %s", name)
	}

	// Test Colors
	if col := getModelColor("grok"); col != colorGrok {
		t.Errorf("Expected colorGrok for grok, got %s", col)
	}
	if col := getModelColor("gemini"); col != colorGemini {
		t.Errorf("Expected colorGemini for gemini, got %s", col)
	}
	if col := getModelColor("claude"); col != colorClaude {
		t.Errorf("Expected colorClaude for claude, got %s", col)
	}
}
